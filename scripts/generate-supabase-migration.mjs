import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const snapshot = JSON.parse(await readFile(resolve(root, "drizzle/meta/0018_snapshot.json"), "utf8"));
const target = resolve(root, "supabase/migrations/20260804000000_d1_to_supabase.sql");

const quote = (name) => `"${name.replaceAll('"', '""')}"`;
const defaultValue = (column) => {
  if (column.default == null) return "";
  if (column.default === "CURRENT_TIMESTAMP") return " DEFAULT (CURRENT_TIMESTAMP::text)";
  if (column.default === false) return " DEFAULT 0";
  return ` DEFAULT ${column.default}`;
};

const statements = [
  "-- Generated from drizzle/meta/0018_snapshot.json for Supabase Postgres.",
  "-- Text dates and integer booleans are preserved for a lossless D1 import.",
];

for (const entry of Object.values(snapshot.tables).sort((a, b) => a.name.localeCompare(b.name))) {
  const columns = Object.values(entry.columns).map((column) => {
    if (column.primaryKey && column.autoincrement) {
      return `  ${quote(column.name)} bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`;
    }
    const type = column.type === "integer" ? "bigint" : "text";
    return `  ${quote(column.name)} ${type}${column.notNull ? " NOT NULL" : ""}${defaultValue(column)}`;
  });
  statements.push(`CREATE TABLE IF NOT EXISTS public.${quote(entry.name)} (\n${columns.join(",\n")}\n);`);
  for (const index of Object.values(entry.indexes ?? {})) {
    const columnsSql = index.columns.map((column) => quote(typeof column === "string" ? column : column.expression)).join(", ");
    statements.push(`CREATE ${index.isUnique ? "UNIQUE " : ""}INDEX IF NOT EXISTS ${quote(index.name)} ON public.${quote(entry.name)} (${columnsSql});`);
  }
  statements.push(`ALTER TABLE public.${quote(entry.name)} ENABLE ROW LEVEL SECURITY;`);
  statements.push(`REVOKE ALL ON TABLE public.${quote(entry.name)} FROM anon, authenticated;`);
}

statements.push("CREATE UNIQUE INDEX IF NOT EXISTS notification_read_unique ON public.notification_reads (notification_id, user_email);");
statements.push("-- Server-side access uses the confidential SUPABASE_DB_URL connection; no Data API policies are granted.");

await mkdir(dirname(target), { recursive: true });
await writeFile(target, `${statements.join("\n\n")}\n`, "utf8");
